def build():
    out = []
    for account, name, objective, spend, cpm_target, ctr, freq, start, end in ROWS:
        advertiser, fmt = ACCOUNTS[account]
        imp = round(spend / cpm_target * 1000)
        cpm = round(spend / imp * 1000)          # 表示用CPMを実数から再計算（整合保証）
        clicks = round(imp * ctr / 100)
        ctr_disp = round(clicks / imp * 100, 2)  # 表示用クリック率も再計算
        reach = round(imp / freq)
        freq_disp = round(imp / reach, 2)
        out.append({
            "advertiser": advertiser,
            "campaign_name": name,
            "ad_account": account,
            "objective": objective,
            "creative_format": fmt,
            "impressions": imp,
            "cpm": cpm,
            "clicks": clicks,
            "ctr": ctr_disp,
            "reach": reach,
            "frequency": freq_disp,
            "spend": spend,
            "start_date": start,
            "end_date": end,
        })
    return out


HEADERS = ["広告主", "キャンペーン名", "広告アカウント", "目的", "クリエイティブ形式",
           "imp", "CPM", "クリック", "クリック率", "リーチ", "フリークエンシー", "消化額",
           "配信開始", "配信終了", "配信期間"]


def tsv(rows):
    lines = ["\t".join(HEADERS)]
    for r in rows:
        lines.append("\t".join([
            r["advertiser"], r["campaign_name"], r["ad_account"], r["objective"],
            r["creative_format"],
            str(r["impressions"]), str(r["cpm"]), str(r["clicks"]),
            f'{r["ctr"]:.2f}%', str(r["reach"]), f'{r["frequency"]:.2f}',
            str(r["spend"]), r["start_date"], r["end_date"],
            f'{r["start_date"]}〜{r["end_date"]}',
        ]))
    return "\n".join(lines) + "\n"


def agg(sub):
    imp = sum(r["impressions"] for r in sub)
    clk = sum(r["clicks"] for r in sub)
    spd = sum(r["spend"] for r in sub)
    return {
        "件数": len(sub),
        "imp合計": imp,
        "imp平均": round(imp / len(sub)),
        "加重CPM": round(spd / imp * 1000),
        "加重クリック率": round(clk / imp * 100, 3),
        "消化額合計": spd,
        "消化額平均": round(spd / len(sub)),
        "消化額min": min(r["spend"] for r in sub),
        "消化額max": max(r["spend"] for r in sub),
    }


def summary(rows):
    out = {}
    for account in ACCOUNTS:
        sub = [r for r in rows if r["ad_account"] == account]
        block = {"__全体__": agg(sub)}
        for obj in dict.fromkeys(r["objective"] for r in sub):
            block[obj] = agg([r for r in sub if r["objective"] == obj])
            block[obj]["着地目安クリック率"] = ANCHORS.get((account, obj))
        ref = REFERENCE.get(account)
        block["__既存参考行__"] = ref if ref else "（手元に無し / 相場で設計）"
        out[account] = block
    out["__全40行__"] = agg(rows)
    return out


if __name__ == "__main__":
    rows = build()
    d = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(d, "campaign_samples.tsv"), "w", encoding="utf-8") as f:
        f.write(tsv(rows))
    with open(os.path.join(d, "campaign_samples.json"), "w", encoding="utf-8") as f:
        json.dump(rows, f, ensure_ascii=False, indent=2)
        f.write("\n")
    json.dump(summary(rows), sys.stdout, ensure_ascii=False, indent=2)
    print()
